"""An index of committed end-to-end runs, and a chart of accuracy against cost.

``docfunnel e2e-summary reports/e2e`` reads every ``<run>/report.json`` under a
directory and writes:

* ``README.md`` in that directory: one row per run, then one row per model and route
  of each run, linked to its report;
* an SVG of exact match against cost per 1,000 documents, for the runs on the full
  document set with the standard prompt, so every point is comparable.

Both are regenerated from the reports, so the published numbers cannot drift from them.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from html import escape
from pathlib import Path

from docfunnel.evals.e2e.report import load_e2e_report
from docfunnel.evals.e2e.runner import E2EReport
from docfunnel.evals.formatting import fmt_pct
from docfunnel.evals.stats import mcnemar_exact_p, wilson_interval

STANDARD_PROMPT = "v2"

MODEL_NAMES = {
    "gpt-6-luna": "GPT-6 Luna",
    "claude-haiku-5-5": "Claude Haiku 5.5",
    "claude-sonnet-5-5": "Claude Sonnet 5.5",
    "gemini-3.1-flash-lite": "Gemini 3.1 Flash-Lite",
    "gemini-3.5-flash-lite": "Gemini 3.5 Flash-Lite",
    "gemini-3.8-flash": "Gemini 3.8 Flash",
    "gemma4:12b-mlx": "Gemma 4 12B (local)",
}

INPUT_KINDS = {
    "text": "parsed text",
    "native": "the file, or page images",
    "hybrid": "the file, or page images",
    "hybrid-ocr": "page images with their OCR text",
}
"""What the model reads on each route, in the chart's three groups."""


@dataclass(frozen=True)
class Run:
    name: str  # directory name, e.g. "07-gpt-6-luna-hybrid-ocr"
    report: E2EReport


@dataclass(frozen=True)
class Outcome:
    """One document's result: exactly right or not, and whether it was sent to review."""

    exact: bool
    review: bool


@dataclass(frozen=True)
class Point:
    model: str
    route: str
    run: str
    exact_match: float
    cost_per_1k: float
    documents: int = 0
    exact: int = 0


def outcomes(report: E2EReport, model: str, route: str) -> dict[str, Outcome]:
    """Per-document outcomes of one model and route, by document id (skipped calls left out)."""
    return {
        row.doc_id: Outcome(row.score.exact_match, row.score.needs_review)
        for row in report.rows
        if row.model == model and row.route == route and row.score is not None
    }


def _ci(exact: int, documents: int) -> str:
    low, high = wilson_interval(exact, documents)
    return f"{low * 100:.0f} to {high * 100:.0f}%"


def load_runs(directory: Path) -> list[Run]:
    """Every ``<run>/report.json`` under ``directory``, in directory-name order."""
    paths = sorted(directory.glob("*/report.json"))
    return [Run(path.parent.name, load_e2e_report(path)) for path in paths]


def model_name(model: str) -> str:
    base, _, variant = model.partition("+")
    name = MODEL_NAMES.get(base, base)
    return f"{name} ({variant.replace('_', ' ')})" if variant else name


# ---- index ------------------------------------------------------------------------


def _spent(report: E2EReport) -> str:
    total = sum(report.meta.spent_usd.values())
    return f"${total:.2f}"


def render_index(runs: list[Run]) -> str:
    """The ``README.md`` for a directory of runs."""
    lines = [
        "# End-to-end runs with real models",
        "",
        "One folder per run, in the order they were made. Each holds `report.json` "
        "(every document's score) and `report.md` (the tables). What each run showed, "
        "and what changed in the code because of it: "
        "[findings](../../docs/evaluation/findings.md). The conclusions: "
        "[proof-of-concept report](../../docs/evaluation/real-models.md).",
        "",
        "This file is generated by `docfunnel e2e-summary reports/e2e`.",
        "",
        "## Runs",
        "",
        "| Run | What it tested | Documents | Prompt | Spent |",
        "| --- | --- | ---: | --- | ---: |",
    ]
    for run in runs:
        meta = run.report.meta
        lines.append(
            f"| [{run.name}]({run.name}/report.md) | {escape(meta.run_name)} "
            f"| {meta.documents} | {meta.prompt_version} | {_spent(run.report)} |"
        )
    total = sum(sum(run.report.meta.spent_usd.values()) for run in runs)
    lines += [
        "",
        f"Total spent, by our price table: ${total:.2f}.",
        "",
        "## Every model and route",
        "",
        "All documents of each run. Exact match: every header field and every line item "
        "right, with its 95% Wilson interval: on 39 documents the true rate can be 10 to "
        "15 points either side of what one run measured. *Wrong, not flagged*: documents "
        "with an error that the business rules did not send to review, so they would have "
        "been accepted. Runs on fewer documents are samples (12) or the invoices with "
        "scanned pages (29), so compare rows within a run.",
        "",
        "| Run | Model | Route | Documents | Exact match | 95% interval | Wrong, not flagged "
        "| Field accuracy | Line items F1 | Cost per 1k docs |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for run in runs:
        for group in run.report.groups:
            if group.slice != "all":
                continue
            m = group.metrics
            cost = "n/a" if m.cost_per_doc_usd is None else f"${m.cost_per_doc_usd * 1000:.2f}"
            docs = outcomes(run.report, group.model, group.route)
            exact = sum(o.exact for o in docs.values())
            wrong = len(docs) - exact
            silent = sum(not o.exact and not o.review for o in docs.values())
            lines.append(
                f"| {run.name} | {model_name(group.model)} | {group.route} | {m.documents} "
                f"| {fmt_pct(m.exact_match_rate)} | {_ci(exact, len(docs))} "
                f"| {silent} of {wrong} | {fmt_pct(m.field_accuracy)} "
                f"| {fmt_pct(m.line_items_f1)} | {cost} |"
            )
    lines += _paired_section(runs)
    return "\n".join(lines) + "\n"


def paired_comparisons(runs: list[Run]) -> list[tuple[Point, Point, int, int, int, float]]:
    """Every pair of routes of one model among the chart's points, on the same documents.

    Returns ``(a, b, documents, only_a_right, only_b_right, p)`` with the exact McNemar
    p-value, the better route first.
    """
    reports = {run.name: run.report for run in runs}
    points = chart_points(runs)
    result = []
    for i, a in enumerate(points):
        for b in points[i + 1 :]:
            if a.model != b.model:
                continue
            first = outcomes(reports[a.run], a.model, a.route)
            second = outcomes(reports[b.run], b.model, b.route)
            shared = sorted(set(first) & set(second))
            only_a = sum(first[d].exact and not second[d].exact for d in shared)
            only_b = sum(second[d].exact and not first[d].exact for d in shared)
            better, other = (a, b) if only_a >= only_b else (b, a)
            hi, lo = max(only_a, only_b), min(only_a, only_b)
            result.append((better, other, len(shared), hi, lo, mcnemar_exact_p(hi, lo)))
    return result


def _paired_section(runs: list[Run]) -> list[str]:
    lines = [
        "",
        "## Paired comparisons",
        "",
        "Two routes of one model on the same documents (the results in the chart). Only "
        "the documents one route got right and the other got wrong say which is better; "
        "*p* is the exact McNemar test on them. With 39 documents, p < 0.05 needs a split "
        "of at least 6 to 0, 8 to 1 or 10 to 2. These are tests on the documents the "
        "routes were developed on, not on new ones.",
        "",
        "| Model | Better route | Other route | Documents | Only the better right "
        "| Only the other right | p |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for a, b, shared, only_a, only_b, p in paired_comparisons(runs):
        lines.append(
            f"| {model_name(a.model)} | {a.route} | {b.route} | {shared} | {only_a} "
            f"| {only_b} | {p:.3f} |"
        )
    return lines


# ---- chart ------------------------------------------------------------------------


def chart_points(runs: list[Run]) -> list[Point]:
    """Model and route results comparable on one chart.

    Runs on the full document set (the most documents of any run), with the standard
    prompt, base models only (no effort or thinking variants), all documents. A model and
    route measured in several runs appears once, from the latest run.
    """
    if not runs:
        return []
    full = max(run.report.meta.documents for run in runs)
    points: dict[tuple[str, str], Point] = {}
    for run in runs:
        meta = run.report.meta
        if meta.documents != full or meta.prompt_version != STANDARD_PROMPT:
            continue
        for group in run.report.groups:
            m = group.metrics
            if group.slice != "all" or "+" in group.model or not m.cost_per_doc_usd:
                continue
            docs = outcomes(run.report, group.model, group.route)
            points[(group.model, group.route)] = Point(
                group.model,
                group.route,
                run.name,
                m.exact_match_rate,
                m.cost_per_doc_usd * 1000,
                len(docs),
                sum(o.exact for o in docs.values()),
            )
    return list(points.values())


_WIDTH, _HEIGHT = 760, 460
_LEFT, _RIGHT, _TOP, _BOTTOM = 64, 24, 92, 56
_X_TICKS = (1.0, 2.0, 5.0, 10.0, 20.0)
_Y_MIN = 0.5
_KIND_CLASSES = {
    "page images with their OCR text": "s1",
    "the file, or page images": "s2",
    "parsed text": "s3",
}

_STYLE = """
  .surface { fill: #fcfcfb; }
  .title { fill: #0b0b0b; font-size: 16px; font-weight: 600; }
  .subtitle, .legend { fill: #52514e; font-size: 12px; }
  .axis-label, .tick { fill: #898781; font-size: 12px; }
  .label { fill: #0b0b0b; font-size: 12px; }
  .label.strong { font-weight: 600; }
  .grid { stroke: #e1e0d9; stroke-width: 1; }
  .baseline { stroke: #c3c2b7; stroke-width: 1; }
  .dot { stroke: #fcfcfb; stroke-width: 2; }
  .link { fill: none; stroke: #c3c2b7; stroke-width: 1.5; stroke-dasharray: 3 3; }
  .ci { stroke-width: 6; stroke-linecap: round; opacity: 0.22; }
  line.s1 { stroke: #2a78d6; } line.s2 { stroke: #eb6834; } line.s3 { stroke: #1baf7a; }
  .s1 { fill: #2a78d6; } .s2 { fill: #eb6834; } .s3 { fill: #1baf7a; }
  @media (prefers-color-scheme: dark) {
    .surface { fill: #1a1a19; }
    .title, .label { fill: #f0efec; }
    .subtitle, .legend { fill: #c3c2b7; }
    .grid { stroke: #2c2c2a; }
    .baseline { stroke: #383835; }
    .dot { stroke: #1a1a19; }
    .link { stroke: #52514e; }
    .s1 { fill: #3987e5; } .s2 { fill: #d95926; } .s3 { fill: #199e70; }
    line.s1 { stroke: #3987e5; } line.s2 { stroke: #d95926; } line.s3 { stroke: #199e70; }
    .ci { opacity: 0.3; }
  }
"""


def _x(cost: float) -> float:
    lo, hi = math.log10(_X_TICKS[0]), math.log10(_X_TICKS[-1])
    span = _WIDTH - _LEFT - _RIGHT
    return _LEFT + (math.log10(cost) - lo) / (hi - lo) * span


def _y(rate: float) -> float:
    span = _HEIGHT - _TOP - _BOTTOM
    return _TOP + (1.0 - rate) / (1.0 - _Y_MIN) * span


@dataclass(frozen=True)
class _Box:
    x0: float
    y0: float
    x1: float
    y1: float

    def hits(self, other: _Box) -> bool:
        return not (
            self.x1 < other.x0 or other.x1 < self.x0 or self.y1 < other.y0 or other.y1 < self.y0
        )


def _text_width(text: str) -> float:
    return len(text) * 6.6  # 12px system sans, close enough to keep labels apart


def _place_label(text: str, cx: float, cy: float, taken: list[_Box]) -> tuple[float, float, str]:
    """A position next to the dot at (cx, cy) that overlaps no placed label or dot."""
    width, height = _text_width(text), 14.0
    candidates = [
        (cx + 9, cy + 4, "start"),
        (cx - 9, cy + 4, "end"),
        (cx, cy - 11, "middle"),
        (cx, cy + 20, "middle"),
        (cx + 9, cy - 10, "start"),
        (cx + 9, cy + 18, "start"),
        (cx - 9, cy - 10, "end"),
        (cx - 9, cy + 18, "end"),
    ]
    for x, y, anchor in candidates:
        x0 = {"start": x, "end": x - width, "middle": x - width / 2}[anchor]
        box = _Box(x0, y - height + 3, x0 + width, y + 3)
        inside = box.x0 >= _LEFT and box.x1 <= _WIDTH - _RIGHT / 2 and box.y0 >= _TOP - 8
        if inside and box.y1 <= _HEIGHT - _BOTTOM and not any(box.hits(t) for t in taken):
            taken.append(box)
            return x, y, anchor
    return candidates[0]


def render_chart(points: list[Point], *, documents: int) -> str:
    """An SVG scatter: exact match (y) against cost per 1,000 documents (x, log scale).

    Colour is what the model read (three groups); a bar behind each dot is its 95% Wilson
    interval. A dashed line joins one model's results, and each model is named next to
    its best one, so identity never rests on colour.
    """
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {_WIDTH} {_HEIGHT}" '
        f'width="{_WIDTH}" height="{_HEIGHT}" role="img" '
        'font-family="system-ui, -apple-system, &quot;Segoe UI&quot;, sans-serif" '
        'aria-labelledby="title desc">',
        f"<style>{_STYLE}</style>",
        '<title id="title">Exact match against cost, by what the model reads</title>',
        f'<desc id="desc">{len(points)} model and route results on {documents} synthetic '
        "invoices. The data is in reports/e2e/README.md.</desc>",
        f'<rect class="surface" width="{_WIDTH}" height="{_HEIGHT}" rx="8"/>',
        f'<text class="title" x="{_LEFT}" y="30">Exact match depends on what the model '
        "reads</text>",
        f'<text class="subtitle" x="{_LEFT}" y="50">Exact match (every field and line item '
        f"right) against cost per 1,000 invoices; {documents} synthetic invoices, one run each. "
        "Bars: 95% interval"
        "</text>",
    ]
    # Legend, in one row under the subtitle.
    x = float(_LEFT)
    for kind, css in _KIND_CLASSES.items():
        out.append(f'<circle class="{css}" cx="{x + 5:.1f}" cy="70" r="5"/>')
        out.append(f'<text class="legend" x="{x + 15:.1f}" y="74">{escape(kind)}</text>')
        x += 15 + _text_width(kind) + 24
    # Grid and axes.
    for rate in (0.5, 0.6, 0.7, 0.8, 0.9, 1.0):
        y = _y(rate)
        css = "baseline" if rate == _Y_MIN else "grid"
        out.append(
            f'<line class="{css}" x1="{_LEFT}" x2="{_WIDTH - _RIGHT}" y1="{y:.1f}" y2="{y:.1f}"/>'
        )
        out.append(
            f'<text class="tick" x="{_LEFT - 8}" y="{y + 4:.1f}" text-anchor="end">'
            f"{rate * 100:.0f}%</text>"
        )
    for cost in _X_TICKS:
        out.append(
            f'<text class="tick" x="{_x(cost):.1f}" y="{_HEIGHT - _BOTTOM + 18}" '
            f'text-anchor="middle">${cost:g}</text>'
        )
    out.append(
        f'<text class="axis-label" x="{_WIDTH - _RIGHT}" y="{_HEIGHT - 12}" text-anchor="end">'
        "Cost per 1,000 invoices (US$, log scale)</text>"
    )
    # Dots, then one label per model at its best point.
    taken = [
        _Box(
            _x(p.cost_per_1k) - 6,
            _y(p.exact_match) - 6,
            _x(p.cost_per_1k) + 6,
            _y(p.exact_match) + 6,
        )
        for p in points
    ]
    by_model: dict[str, list[Point]] = {}
    for p in points:
        by_model.setdefault(p.model, []).append(p)
    for model_points in by_model.values():
        path = sorted(model_points, key=lambda p: p.exact_match)
        coords = " ".join(f"{_x(p.cost_per_1k):.1f},{_y(p.exact_match):.1f}" for p in path)
        out.append(f'<polyline class="link" points="{coords}"/>')
    for p in points:
        css = _KIND_CLASSES[INPUT_KINDS.get(p.route, "parsed text")]
        low, high = wilson_interval(p.exact, p.documents)
        x = _x(p.cost_per_1k)
        out.append(
            f'<line class="ci {css}" x1="{x:.1f}" x2="{x:.1f}" '
            f'y1="{_y(max(low, _Y_MIN)):.1f}" y2="{_y(high):.1f}"/>'
        )
    for p in sorted(points, key=lambda p: p.exact_match):
        css = _KIND_CLASSES[INPUT_KINDS.get(p.route, "parsed text")]
        tip = (
            f"{model_name(p.model)}, {p.route} route ({p.run}): "
            f"{fmt_pct(p.exact_match)} exact match, ${p.cost_per_1k:.2f} per 1k invoices"
        )
        out.append(
            f'<circle class="dot {css}" cx="{_x(p.cost_per_1k):.1f}" '
            f'cy="{_y(p.exact_match):.1f}" r="6"><title>{escape(tip)}</title></circle>'
        )
    best: dict[str, Point] = {}
    for p in points:
        if p.model not in best or p.exact_match > best[p.model].exact_match:
            best[p.model] = p
    top = max(points, key=lambda p: p.exact_match, default=None)
    for p in sorted(best.values(), key=lambda p: (-p.exact_match, p.cost_per_1k)):
        text = model_name(p.model)
        if p is top:
            text += f", {p.route}: {fmt_pct(p.exact_match)}"
        lx, ly, anchor = _place_label(text, _x(p.cost_per_1k), _y(p.exact_match), taken)
        strong = " strong" if p is top else ""
        out.append(
            f'<text class="label{strong}" x="{lx:.1f}" y="{ly:.1f}" text-anchor="{anchor}">'
            f"{escape(text)}</text>"
        )
    out.append("</svg>")
    return "\n".join(out) + "\n"


def write_summary(directory: Path, chart_path: Path) -> tuple[Path, Path]:
    """Write ``directory/README.md`` and the chart; return both paths."""
    runs = load_runs(directory)
    if not runs:
        raise FileNotFoundError(f"no */report.json under {directory}")
    index = directory / "README.md"
    index.write_text(render_index(runs))
    points = chart_points(runs)
    documents = max(run.report.meta.documents for run in runs)
    chart_path.parent.mkdir(parents=True, exist_ok=True)
    chart_path.write_text(render_chart(points, documents=documents))
    return index, chart_path
